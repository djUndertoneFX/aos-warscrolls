// usage: node emitFactionPaths.js [faction-paths.json]
// faction-paths.json = { <faction_slug>: [{ name, restricted, ranks: [{ rank, options: [...] }] }] },
// pulled in the browser from each wahapedia.ru/aos4/factions/<slug>/ page's
// Path to Glory "Path of …" sections (h1 headings inside Corner22 boxes).
// Writes ../../frontend/src/components/ptgFactionPaths.js.
const fs = require('fs');
const path = require('path');
const { resolvePhaseKeyString } = require('../phaseKey');

const src = JSON.parse(fs.readFileSync(process.argv[2] || path.join(__dirname, 'faction-paths.json'), 'utf8'));
// Wahapedia typos in the restriction lines.
const FIX_RESTRICTED = {
  'cities-of-sigmar': s => s.replace('SLAVES TO DARKNESS', 'CITIES OF SIGMAR'),
  'stormcast-eternals': s => s.replace('ETHERNALS', 'ETERNALS'),
};
const out = {};
for (const [slug, paths] of Object.entries(src)) {
  if (!Array.isArray(paths) || !paths.length) continue;
  out[slug] = paths.map(p => {
    const restricted = (FIX_RESTRICTED[slug] || (s => s))(p.restricted || '').replace(/^NON-/, 'non-');
    // HERO-only Paths are Hero Paths, non-HERO ones Unit Paths; anything else
    // (Sons of Behemat's LITTLE / BIG) is offered to both.
    const hero = /non-\s*HERO/i.test(restricted) || /SKYVESSEL/.test(restricted) ? false : /\bHERO\b/.test(restricted) ? true : undefined;
    const key = `${slug}-${p.name.toLowerCase().replace(/^path of (the )?/, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`;
    const ranks = p.ranks.map(r => ({
      rank: r.rank,
      options: r.options.map(o => {
        const opt = { ...o };
        for (const k of Object.keys(opt)) if (opt[k] === '' || opt[k] == null) delete opt[k];
        try { const pk = resolvePhaseKeyString({ ...opt, bullets: '[]' }); if (pk) opt.phase_key = pk; } catch {}
        return opt;
      }),
    }));
    const entry = { key, name: p.name, restricted };
    if (hero !== undefined) entry.hero = hero;
    entry.ranks = ranks;
    return entry;
  });
}
const file = path.join(__dirname, '../../frontend/src/components/ptgFactionPaths.js');
fs.writeFileSync(file, `// GENERATED by backend/tools/emitFactionPaths.js from Wahapedia faction pages
// (Path to Glory: the faction's own Hero Path and Unit Path(s)). Do not edit by hand.
const FACTION_PATHS_SCRAPED = ${JSON.stringify(out, null, 1)};
export default FACTION_PATHS_SCRAPED;
`);
for (const [s, ps] of Object.entries(out)) console.log(s.padEnd(24), ps.map(p => `${p.name} (${p.hero === true ? 'hero' : p.hero === false ? 'unit' : 'both'})`).join(' | '));
