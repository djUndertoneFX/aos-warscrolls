import React, { useEffect, useMemo, useRef, useState } from 'react';
import axios from 'axios';
import { AbilityCard } from '../components/WarscrollGW';
import VoiceControlWidget from '../components/VoiceControlWidget';
import GHB from '../matchedPlayData';

// ── Matched Play (General's Handbook 2026-27) ────────────────────────────────
// A game companion for a matched play battle: pick both armies (your Army
// Builder lists), roll or pick the battleplan, pick battle tactics cards,
// then keep score round by round — battleplan VP, battle tactics (Affray →
// Strike → Domination, one per card per turn, none while seizing the
// initiative), fury level / rage dice from the season rules — with the
// Glorious Victory result worked out at the end. Data: matchedPlayData.js
// (generated by backend/tools/extractGhb.js). The whole game is saved to
// the account (/api/matched-play-state) so it follows you between devices,
// with localStorage as an offline fallback.

const STORE_KEY = 'aos-matched-play';
const ROUNDS = 5;
const SIDES = ['you', 'opp'];
const SIDE_LABEL = { you: 'You', opp: 'Opponent' };
const TIERS = ['Affray', 'Strike', 'Domination'];

// Core battlepack rules, condensed (General's Handbook 2026-27 battlepack).
const CORE_RULES = [
  'Armies: built with Army Composition 2026-27 — usually 2000 points (1000-point games are supported). Each army picks up to 2 battle tactics cards, written on the roster and revealed before deployment.',
  'Battleplan: one player rolls a dice — 1-3 uses table 1, 4-6 table 2 — then the other player rolls for the battleplan on that table (or just agree on one).',
  'Attacker and defender: roll off; the winner chooses. The defender sets up the Aqshian objectives where the map shows (3" control zones) and the terrain (we recommend 4 small + 4 medium, more than 3" from edges and objectives and more than 6" from each other). The attacker then picks their territory and deploys first.',
  'The battle lasts 5 battle rounds. Battlefield: 44" × 60" with 8 terrain features (30" × 44" with 4 for 1000 points is fine).',
  'Battle tactics: 3 per card (Affray, then Strike, then Domination). At the end of each of your turns you can complete 1 tactic per card, and you must complete one if you meet its conditions. 5 VP each.',
  'Seizing the initiative: going second in a round, then winning priority and choosing to go first in the next (unless your opponent leads by 11+ VP). You can’t complete battle tactics that turn, and your opponent counts as the underdog until they seize the initiative themselves.',
  'Glorious Victory: 5+ VP more than your opponent is a major victory, fewer is a minor victory. Tied on VP: whoever completed more battle tactics wins a minor victory; otherwise it’s a draw.',
];

const blankGame = () => ({
  stage: 'armies',
  points: 2000,
  lists: { you: '', opp: '' },
  attacker: '',              // 'you' | 'opp' | ''
  tableRoll: null, planRoll: null,
  battleplan: '',            // battleplan name
  cards: { you: [], opp: [] }, // up to 2 card names each
  // rounds[r][side] = { vp, seized, tactics: { [cardName]: tierName } }
  rounds: Array.from({ length: ROUNDS }, () => ({ you: { vp: 0, seized: false, tactics: {} }, opp: { vp: 0, seized: false, tactics: {} } })),
  fury: { you: 0, opp: 0 },
  rage: { you: 0, opp: 0 },
  currentRound: 0,
});

const d6 = () => 1 + Math.floor(Math.random() * 6);
const parseBullets = b => { if (Array.isArray(b)) return b; try { return JSON.parse(b || '[]'); } catch { return []; } };

function TacticsCard({ card, pickedBy, onToggle, completed }) {
  return (
    <div className={`mp-tactics-card${pickedBy.length ? ' mp-picked' : ''}`}>
      <div className="mp-tactics-card-head">
        <div className="mp-tactics-card-name">{card.name}</div>
        {onToggle && (
          <div className="mp-pick-btns">
            {SIDES.map(s => (
              <button key={s} type="button" className={`mp-pick-btn mp-pick-${s}${pickedBy.includes(s) ? ' active' : ''}`} onClick={() => onToggle(s)}>
                {pickedBy.includes(s) ? '✓ ' : '+ '}{SIDE_LABEL[s]}
              </button>
            ))}
          </div>
        )}
      </div>
      <div className="mp-tactics-flavor">{card.flavor}</div>
      {card.setup && <div className="mp-tactics-setup">{card.setup}</div>}
      {card.tactics.map(t => (
        <div key={t.tier} className={`mp-tactic mp-tier-${t.tier.toLowerCase()}${completed && completed.includes(t.tier) ? ' mp-done' : ''}`}>
          <div className="mp-tactic-head"><span className="mp-tactic-tier">{t.tier}</span> {t.name}<span className="mp-tactic-vp">{t.vp} VP</span></div>
          <div className="mp-tactic-cond">{t.condition.split('\n').map((l, i) => <div key={i}>{l}</div>)}</div>
        </div>
      ))}
    </div>
  );
}

export default function MatchedPlayPage() {
  const [game, setGame] = useState(() => {
    try { return { ...blankGame(), ...(JSON.parse(localStorage.getItem(STORE_KEY)) || {}) }; } catch { return blankGame(); }
  });
  const [lists, setLists] = useState([]);
  const [rolling, setRolling] = useState(false);
  const loaded = useRef(false);
  const saveTimer = useRef(null);

  // Load: the account's saved game (if any) wins over this browser's copy.
  useEffect(() => {
    axios.get('/api/army-builder-lists').then(r => setLists(r.data || [])).catch(() => {});
    axios.get('/api/matched-play-state').then(r => {
      if (r.data && r.data.data) setGame({ ...blankGame(), ...r.data.data });
    }).catch(() => {}).finally(() => { loaded.current = true; });
  }, []);

  // Save: localStorage immediately, server debounced.
  useEffect(() => {
    try { localStorage.setItem(STORE_KEY, JSON.stringify(game)); } catch {}
    if (!loaded.current) return;
    if (saveTimer.current) clearTimeout(saveTimer.current);
    saveTimer.current = setTimeout(() => { axios.put('/api/matched-play-state', { data: game }).catch(() => {}); }, 800);
    return () => clearTimeout(saveTimer.current);
  }, [game]);

  const set = patch => setGame(g => ({ ...g, ...(typeof patch === 'function' ? patch(g) : patch) }));
  const plan = GHB.battleplans.find(b => b.name === game.battleplan) || null;
  const ownLists = lists.filter(l => (l.list_type || 'own') !== 'enemy');
  const enemyLists = lists.filter(l => l.list_type === 'enemy');
  const listName = id => lists.find(l => String(l.id) === String(id));

  // ── scoring ──
  const tacticsDoneBefore = (side, card, uptoRound) => {
    const done = [];
    for (let r = 0; r < uptoRound; r++) { const t = game.rounds[r][side].tactics[card]; if (t) done.push(t); }
    return done;
  };
  const totals = useMemo(() => {
    const out = {};
    for (const s of SIDES) {
      let vp = 0, tactics = 0;
      for (const r of game.rounds) {
        vp += Number(r[s].vp) || 0;
        const n = Object.values(r[s].tactics).filter(Boolean).length;
        tactics += n; vp += n * 5;
      }
      out[s] = { vp, tactics };
    }
    return out;
  }, [game.rounds]);
  const result = (() => {
    const { you, opp } = totals;
    const diff = you.vp - opp.vp;
    if (diff !== 0) return { winner: diff > 0 ? 'you' : 'opp', kind: Math.abs(diff) >= 5 ? 'Major victory' : 'Minor victory' };
    if (you.tactics !== opp.tactics) return { winner: you.tactics > opp.tactics ? 'you' : 'opp', kind: 'Minor victory (more battle tactics)' };
    return { winner: null, kind: 'Draw' };
  })();

  const setRound = (r, side, patch) => set(g => {
    const rounds = g.rounds.map((x, i) => (i === r ? { ...x, [side]: { ...x[side], ...patch } } : x));
    return { rounds };
  });
  const toggleTactic = (r, side, card) => {
    const done = tacticsDoneBefore(side, card.name, r);
    const cur = game.rounds[r][side].tactics[card.name];
    let next = null;
    if (!cur) {
      next = TIERS.find(t => !done.includes(t)) || null; // next tier in order
      if (!next) return;
    }
    // Tiers go in order through the rounds, so a round can only be changed
    // while no later round has a tactic from the same card ticked.
    if (game.rounds.slice(r + 1).some(x => x[side].tactics[card.name])) return;
    setRound(r, side, { tactics: { ...game.rounds[r][side].tactics, [card.name]: next } });
  };

  const rollBattleplan = () => {
    setRolling(true);
    let n = 0;
    const iv = setInterval(() => {
      set({ tableRoll: d6(), planRoll: d6() });
      if (++n >= 8) {
        clearInterval(iv);
        const t = d6(), p = d6();
        const table = t <= 3 ? 1 : 2;
        const bp = GHB.battleplans.find(b => b.table === table && b.roll === p);
        set({ tableRoll: t, planRoll: p, battleplan: bp ? bp.name : '' });
        setRolling(false);
      }
    }, 70);
  };
  const toggleCard = (side, name) => set(g => {
    const cur = g.cards[side] || [];
    const next = cur.includes(name) ? cur.filter(c => c !== name) : cur.length >= 2 ? cur : [...cur, name];
    return { cards: { ...g.cards, [side]: next } };
  });
  const setAttacker = side => set(g => ({
    attacker: side,
    // Season rule 'Raising the Heat': attacker starts at fury 1, defender at 2.
    fury: side ? { [side]: 1, [side === 'you' ? 'opp' : 'you']: 2 } : g.fury,
  }));
  const newGame = () => { if (window.confirm('Start a new game? This clears the current scores, battleplan and picks.')) setGame({ ...blankGame(), lists: game.lists, points: game.points }); };

  const STAGES = [
    ['armies', '1 Armies'], ['battleplan', '2 Battleplan'], ['tactics', '3 Battle Tactics'], ['score', '4 Scoreboard'], ['rules', 'Rules'],
  ];

  const Stepper = ({ value, onChange, min = 0, max = 99 }) => (
    <span className="ab-count-stepper mp-stepper">
      <button type="button" className="ab-count-btn" onClick={() => onChange(Math.max(min, (Number(value) || 0) - 1))}>−</button>
      <span className="ab-count-value">{value}</span>
      <button type="button" className="ab-count-btn" onClick={() => onChange(Math.min(max, (Number(value) || 0) + 1))}>+</button>
    </span>
  );

  return (
    <div className="table-page mp-page">
      <div className="page-header mp-header">
        <div className="page-title">Matched Play<span>{GHB.source}</span></div>
        <div className="mp-stages">
          {STAGES.map(([k, l]) => (
            <button key={k} type="button" className={`ab-stage-tab${game.stage === k ? ' active' : ''}`} onClick={() => set({ stage: k })}>{l}</button>
          ))}
        </div>
        <div className="mp-score-mini" title="Victory points (battleplan + battle tactics)">
          <span className="mp-you">{totals.you.vp}</span> – <span className="mp-opp">{totals.opp.vp}</span>
          <div className="mp-score-mini-label">Round {game.currentRound + 1}{plan ? ` · ${plan.name}` : ''}</div>
        </div>
        <button type="button" className="share-btn" onClick={newGame}>New Game</button>
        <VoiceControlWidget />
      </div>

      {game.stage === 'armies' && (
        <div className="mp-section">
          <div className="mp-grid-2">
            {SIDES.map(s => (
              <div key={s} className={`mp-panel mp-panel-${s}`}>
                <div className="mp-panel-title">{s === 'you' ? 'Your Army' : 'Opponent’s Army'}</div>
                <label className="filter-label">Army Builder list</label>
                <select className="filter-select" value={game.lists[s]} onChange={e => set(g => ({ lists: { ...g.lists, [s]: e.target.value } }))}>
                  <option value="">— pick a list —</option>
                  {(s === 'you' ? ownLists : [...enemyLists, ...ownLists]).map(l => (
                    <option key={l.id} value={l.id}>{l.list_type === 'enemy' ? 'Enemy: ' : ''}{l.name}{l.faction_name ? ` — ${l.faction_name}` : ''}</option>
                  ))}
                </select>
                {game.lists[s] && listName(game.lists[s]) && (
                  <div className="mp-list-meta">{listName(game.lists[s]).faction_name || 'No faction yet'} · <a href="/army-builder">open in Army Builder</a></div>
                )}
                <div className="mp-row">
                  <span className="filter-label">Battle tactics cards</span>
                  <span>{(game.cards[s] || []).join(', ') || '— pick on step 3 —'}</span>
                </div>
              </div>
            ))}
          </div>
          <div className="mp-panel">
            <div className="mp-row">
              <span className="filter-label">Points limit</span>
              {[1000, 2000].map(p => (
                <button key={p} type="button" className={`page-btn${game.points === p ? ' active' : ''}`} onClick={() => set({ points: p })}>{p}</button>
              ))}
              <span className="mp-hint">{game.points === 1000 ? '30" × 44" with 4 terrain features is fine' : '44" × 60" with 8 terrain features'}</span>
            </div>
            <div className="mp-row">
              <span className="filter-label">Attacker</span>
              {SIDES.map(s => (
                <button key={s} type="button" className={`page-btn${game.attacker === s ? ' active' : ''}`} onClick={() => setAttacker(s)}>{SIDE_LABEL[s]}</button>
              ))}
              <span className="mp-hint">Roll off — the winner chooses. The defender sets up objectives and terrain; the attacker picks a territory and deploys first.</span>
            </div>
          </div>
          <button type="button" className="ptg-wizard-nav-btn" onClick={() => set({ stage: 'battleplan' })}>Next: Battleplan ›</button>
        </div>
      )}

      {game.stage === 'battleplan' && (
        <div className="mp-section">
          <div className="mp-row">
            <button type="button" className="ptg-wizard-nav-btn ab-roster-print-confirm" onClick={rollBattleplan} disabled={rolling}>🎲 Roll Battleplan</button>
            {game.tableRoll && (
              <span className="mp-dice">
                <span className="mp-die">{game.tableRoll}</span> table {game.tableRoll <= 3 ? 1 : 2}
                <span className="mp-die">{game.planRoll}</span> battleplan
              </span>
            )}
            <span className="mp-hint">…or pick one below.</span>
          </div>
          <div className="mp-grid-2">
            {[1, 2].map(t => (
              <div key={t} className="mp-panel">
                <div className="mp-panel-title">Battleplan Table {t}</div>
                {GHB.battleplans.filter(b => b.table === t).map(b => (
                  <button key={b.name} type="button" className={`mp-plan-row${game.battleplan === b.name ? ' active' : ''}`} onClick={() => set({ battleplan: b.name })}>
                    <span className="mp-die mp-die-small">{b.roll}</span>{b.name}
                  </button>
                ))}
              </div>
            ))}
          </div>
          {plan && (
            <div className="mp-panel mp-plan-detail">
              <div className="mp-panel-title">{plan.name} <span className="mp-hint">Table {plan.table}, roll {plan.roll}</span></div>
              <div className="mp-plan-twist"><strong>Twist:</strong> {plan.twist}</div>
              <div className="ptg-apotheosis-options-grid">
                {plan.abilities.map((a, i) => <div key={i} className="mp-ability"><AbilityCard ab={{ ...a, bullets: parseBullets(a.bullets) }} keywords={[]} /></div>)}
              </div>
              <div className="mp-panel-subtitle">Scoring — at the end of each of your turns:</div>
              <ul className="ptg-bp-list">{plan.scoring.map((s, i) => <li key={i}>{s}</li>)}</ul>
              <div className="mp-hint">Objective and terrain positions follow the battleplan’s map in the General’s Handbook.</div>
            </div>
          )}
          <button type="button" className="ptg-wizard-nav-btn" onClick={() => set({ stage: 'tactics' })}>Next: Battle Tactics ›</button>
        </div>
      )}

      {game.stage === 'tactics' && (
        <div className="mp-section">
          <div className="mp-hint">Each army picks up to 2 cards (written on the roster, revealed before deployment).</div>
          <div className="mp-cards-grid">
            {GHB.tactics_cards.map(c => (
              <TacticsCard
                key={c.name}
                card={c}
                pickedBy={SIDES.filter(s => (game.cards[s] || []).includes(c.name))}
                onToggle={s => toggleCard(s, c.name)}
              />
            ))}
          </div>
          <button type="button" className="ptg-wizard-nav-btn" onClick={() => set({ stage: 'score' })}>Next: Scoreboard ›</button>
        </div>
      )}

      {game.stage === 'score' && (
        <div className="mp-section">
          <div className="mp-result">
            <span className="mp-you">{SIDE_LABEL.you} {totals.you.vp} VP</span>
            <span className="mp-result-kind">{result.winner ? `${result.kind}: ${result.winner === 'you' ? 'You' : 'Opponent'}` : result.kind}</span>
            <span className="mp-opp">{totals.opp.vp} VP {SIDE_LABEL.opp}</span>
          </div>
          <div className="mp-grid-2">
            {SIDES.map(s => (
              <div key={s} className={`mp-panel mp-panel-${s}`}>
                <div className="mp-panel-title">{SIDE_LABEL[s]} — season rules</div>
                <div className="mp-row"><span className="filter-label">Fury level</span><Stepper value={game.fury[s]} min={0} max={7} onChange={v => set(g => ({ fury: { ...g.fury, [s]: v } }))} />
                  <span className="filter-label">Rage dice</span><Stepper value={game.rage[s]} min={0} max={20} onChange={v => set(g => ({ rage: { ...g.rage, [s]: v } }))} />
                  <button type="button" className="page-btn" title="Simmering Rage: gain rage dice equal to your fury level" onClick={() => set(g => ({ rage: { ...g.rage, [s]: g.fury[s] } }))}>Start of round</button>
                </div>
              </div>
            ))}
          </div>
          <table className="mp-score-table">
            <thead>
              <tr>
                <th>Round</th>
                {SIDES.map(s => <th key={s} className={`mp-th-${s}`} colSpan={3}>{SIDE_LABEL[s]}</th>)}
              </tr>
              <tr className="mp-subhead">
                <th></th>
                {SIDES.map(s => (
                  <React.Fragment key={s}><th>Battleplan VP</th><th>Battle tactics</th><th>Seized?</th></React.Fragment>
                ))}
              </tr>
            </thead>
            <tbody>
              {game.rounds.map((r, ri) => (
                <tr key={ri} className={ri === game.currentRound ? 'mp-current' : ''} onClick={() => set({ currentRound: ri })}>
                  <td className="mp-round-num">{ri + 1}</td>
                  {SIDES.map(s => (
                    <React.Fragment key={s}>
                      <td><Stepper value={r[s].vp} max={30} onChange={v => setRound(ri, s, { vp: v })} /></td>
                      <td><div className="mp-tactic-cells">
                        {(game.cards[s] || []).length === 0 && <span className="mp-hint">no cards picked</span>}
                        {(game.cards[s] || []).map(name => {
                          const card = GHB.tactics_cards.find(c => c.name === name);
                          if (!card) return null;
                          const doneTier = r[s].tactics[name];
                          const before = tacticsDoneBefore(s, name, ri);
                          const nextTier = TIERS.find(t => !before.includes(t));
                          const disabled = r[s].seized || (!doneTier && !nextTier);
                          const t = card.tactics.find(x => x.tier === (doneTier || nextTier));
                          return (
                            <button
                              key={name}
                              type="button"
                              disabled={disabled}
                              className={`mp-tactic-chip${doneTier ? ' done' : ''}`}
                              title={t ? `${card.name} — ${t.tier}: ${t.name}\n${t.condition}` : `${card.name}: all 3 completed`}
                              onClick={e => { e.stopPropagation(); toggleTactic(ri, s, card); }}
                            >
                              {doneTier ? '✓ ' : ''}{t ? `${t.tier}: ${t.name}` : `${card.name} ✓✓✓`}
                            </button>
                          );
                        })}
                      </div></td>
                      <td>
                        <input
                          type="checkbox"
                          checked={!!r[s].seized}
                          title="Seized the initiative this round — no battle tactics this turn"
                          onClick={e => e.stopPropagation()}
                          onChange={e => setRound(ri, s, { seized: e.target.checked, ...(e.target.checked ? { tactics: {} } : {}) })}
                        />
                      </td>
                    </React.Fragment>
                  ))}
                </tr>
              ))}
            </tbody>
            <tfoot>
              <tr>
                <td>Total</td>
                {SIDES.map(s => (
                  <td key={s} colSpan={3} className={`mp-total mp-${s}`}>{totals[s].vp} VP <span className="mp-hint">({totals[s].tactics} battle tactics = {totals[s].tactics * 5} VP)</span></td>
                ))}
              </tr>
            </tfoot>
          </table>
          {plan && (
            <div className="mp-panel">
              <div className="mp-panel-subtitle">{plan.name} scoring — at the end of each of your turns:</div>
              <ul className="ptg-bp-list">{plan.scoring.map((s, i) => <li key={i}>{s}</li>)}</ul>
            </div>
          )}
        </div>
      )}

      {game.stage === 'rules' && (
        <div className="mp-section">
          <div className="mp-panel">
            <div className="mp-panel-title">General’s Handbook 2026-27 battlepack</div>
            <ul className="ptg-bp-list">{CORE_RULES.map((t, i) => <li key={i}>{t}</li>)}</ul>
          </div>
          <div className="mp-panel">
            <div className="mp-panel-title">Season Rules 2026-27 — both players</div>
            <div className="ptg-apotheosis-options-grid">
              {GHB.season_abilities.map((a, i) => <div key={i} className="mp-ability"><AbilityCard ab={{ ...a, bullets: parseBullets(a.bullets) }} keywords={[]} /></div>)}
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
